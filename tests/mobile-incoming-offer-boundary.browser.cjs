// Actual mobile Messages/detail fixture; no hosted sessions, data or API writes.
/* global window, document, getComputedStyle */
const fs = require('node:fs'),
  path = require('node:path'),
  assert = require('node:assert/strict')
const original = fs.readFileSync(
  path.join(__dirname, 'messages-focused-mobile.browser.cjs'),
  'utf8'
)
new Function(
  'require',
  original.slice(0, original.indexOf('async function run()'))
)(require)
const { root, build } = require('./message-payload.browser.cjs')
// The helper import writes its default entry; restore the focused fixture below.
new Function(
  'require',
  original.slice(0, original.indexOf('async function run()'))
)(require)
let entry = fs.readFileSync(path.join(root, 'entry.tsx'), 'utf8')
entry = entry.replace(
  'window.offerHistory={offers:[],agreements:[]};',
  `
const terms={itemAmountCents:8000,currency:'CAD',note:'',fulfillment:'on_campus',meetupLocation:'Weldon',scheduledAt:'2099-10-01T12:00:00Z'};
window.offerHistory={offers:['Active','Replaced','Accepted','Closed','Expired'].flatMap((status,i)=>['buyer','seller'].map(sender=>({id:status+sender,protocolVersion:2,conversationId:'conversation-'+destination,listingId:'listing',buyerId:'buyer',sellerId:'seller',senderId:sender,recipientId:sender==='buyer'?'seller':'buyer',status,terms,askingPriceCents:8000,linkedOrderId:status==='Accepted'?'order':null,canWithdraw:false,canAccept:false,changedFields:['Price'],mutationKind:'create',createdAt:new Date(Date.parse('2026-10-01T12:01:00Z')+i*60000).toISOString()}))),agreements:[]};`
)
fs.writeFileSync(path.join(root, 'entry.tsx'), entry)
async function run() {
  const aliases = require('./browser-fixture-mocks.cjs')(root)
  // Reuse exactly the isolated imports generated by the focused-detail test.
  const names = [
    '@/components/listings/marketplace-session',
    '@/components/loader/loader',
    '@/components/navigation/desktop-route-transition',
    '@/components/home/order-visual-context',
    '@/hooks/use-formal-order-requests',
    '@/hooks/use-formal-offers',
    '@/lib/messages-realtime',
    '@/lib/messages-api',
  ]
  names.forEach(
    (name, i) => (aliases[name] = path.join(root, 'focused-' + i + '.js'))
  )
  aliases['./order-visual-context'] =
    aliases['@/components/home/order-visual-context']
  await build(aliases)
  for (const n of ['entry.tsx', 'api.ts']) fs.unlinkSync(path.join(root, n))
  const {
    chromium,
  } = require('./artifacts/browser-tools/node_modules/playwright-core')
  const b = await chromium.launch({
    executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe',
    headless: true,
  })
  try {
    for (const width of [390, 430, 1280, 1536]) {
      const p = await b.newPage({
        viewport: { width, height: 900 },
        reducedMotion: 'reduce',
      })
      const errors = []
      p.on('pageerror', (e) => errors.push(e.message))
      await p.route(/^https?:/, (r) => r.abort())
      await p.addInitScript(
        () =>
          (window.process = {
            env: {
              NEXT_PUBLIC_MESSAGES_ENV: 'staging',
              NEXT_PUBLIC_SUPABASE_URL:
                'https://pcaqxezdfxofysghssyo.supabase.co',
            },
          })
      )
      await p.goto(
        'file:///' + path.join(root, 'index.html').replaceAll('\\', '/')
      )
      for (const destination of ['buying', 'selling']) {
        await p.evaluate((v) => window.show(v), destination)
        if (width < 1024) await p.locator('[data-conversation-id]').click()
        await p.locator('[data-offer-own]').first().waitFor()
        await p.locator('[class*="messagePayload"]').first().waitFor()
        const values = await p.evaluate(() => {
          const body = document.querySelector('[data-message-history]'),
            composer = document.querySelector('[class*="composer"]'),
            text = document.querySelector('[class*="messagePayload"]')
          const measure = () => ({
            text: text.getBoundingClientRect().toJSON(),
            composer: composer.getBoundingClientRect().toJSON(),
            cards: [...body.querySelectorAll('[data-offer-own]')].map((e) => {
              const r = e.getBoundingClientRect(),
                card = e.querySelector('[class*="offerButton"]'),
                badge = e.querySelector('[class*="offerStatus"]'),
                c = card.getBoundingClientRect(),
                s = badge.getBoundingClientRect()
              return {
                own: e.dataset.offerOwn,
                status: e.dataset.offerStatus,
                x: r.x,
                width: r.width,
                height: r.height,
                card: c.toJSON(),
                gap: c.top - s.bottom,
                badgeRight: s.right,
                clipLeft: body.getBoundingClientRect().left,
                padding: getComputedStyle(card).padding,
                radius: getComputedStyle(card).borderRadius,
              }
            }),
          })
          const after = measure()
          const style = document.createElement('style')
          style.textContent =
            '[data-mobile-message-detail="true"] [data-sent="false"]:has([data-offer-own="false"]){padding-left:0!important}'
          document.head.appendChild(style)
          const before = measure()
          style.remove()
          return { after, before }
        })
        if (process.env.OFFER_BOUNDARY_AUDIT) {
          console.log(JSON.stringify({ width, destination, values }))
          continue
        }
        assert.deepEqual(values.after.text, values.before.text)
        assert.deepEqual(values.after.composer, values.before.composer)
        for (let i = 0; i < values.after.cards.length; i++) {
          const a = values.after.cards[i],
            old = values.before.cards[i]
          if (a.own === 'false' && width < 1024) {
            assert.equal(a.x - old.x, 4)
            assert(a.card.left >= a.clipLeft + 4)
            assert.equal(a.width, old.width)
            assert.equal(a.height, old.height)
            assert.equal(a.card.width, old.card.width)
            assert.equal(a.badgeRight, a.card.right)
            assert.equal(a.gap, 4)
            assert.equal(a.padding, old.padding)
            assert.equal(a.radius, old.radius)
          } else assert.deepEqual(a, old)
        }
        assert(
          await p.evaluate(
            () => document.documentElement.scrollWidth <= window.innerWidth
          )
        )
        if (width < 1024) {
          for (const status of [
            'Active',
            'Replaced',
            'Accepted',
            'No longer available',
            'Expired',
          ]) {
            const card = p.locator(
              '[data-offer-own="false"][data-offer-status="' + status + '"]'
            )
            await card.scrollIntoViewIfNeeded()
            await card.screenshot({
              path: path.join(
                root,
                'left-offer-' +
                  width +
                  '-' +
                  status.replaceAll(' ', '-') +
                  '.png'
              ),
            })
          }
        }
        assert.deepEqual(errors, [])
        console.log(
          'PASS ' +
            width +
            ' ' +
            destination +
            ': incoming Offer boundary, unchanged card widths/status gap/TEXT/right Offer/composer; offline.'
        )
      }
      await p.close()
    }
  } finally {
    await b.close()
  }
}
run().catch((e) => {
  console.error(e)
  process.exitCode = 1
})
